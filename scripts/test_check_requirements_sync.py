#!/usr/bin/env python3
"""Tests for check_requirements_sync.py. Stdlib only, like the guard.

Run from the repo root:
    python3 -m unittest scripts/test_check_requirements_sync.py
"""

import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_requirements_sync as guard  # noqa: E402

LOCK_HEADER = "# autogenerated by pip-compile\n"


def lock_line(name: str, version: str) -> str:
    return f"{name}=={version} \\\n    --hash=sha256:{'0' * 64}\n"


class SatisfiesTest(unittest.TestCase):
    def test_operators(self):
        cases = [
            ("1.3.0", ">=", "1.4.0", False),
            ("1.4.0", ">=", "1.4.0", True),
            ("1.4", ">=", "1.4.0", True),
            ("1.10.0", ">", "1.9.9", True),
            ("2026.10.23", "<", "2026.9.29", False),
            ("1.4.5", "~=", "1.4.2", True),
            ("1.5.0", "~=", "1.4.2", False),
            ("1.4.1", "~=", "1.4.2", False),
            ("1.4.7", "==", "1.4.*", True),
            ("1.5.0", "!=", "1.4.*", True),
            ("1.0rc1", "<", "1.0", True),
        ]
        for version, op, wanted, expected in cases:
            with self.subTest(f"{version} {op} {wanted}"):
                self.assertIs(guard.satisfies(version, op, wanted), expected)

    def test_unparseable_specifier_raises(self):
        with self.assertRaises(ValueError):
            guard.extract_specifiers("pkg@https://example.invalid/pkg.whl")


class MainTest(unittest.TestCase):
    def run_guard(self, req: str, ci: str, lock: str) -> tuple[int, str]:
        with tempfile.TemporaryDirectory() as tmp:
            paths = {}
            for name, body in (
                ("requirements.txt", req),
                ("requirements-ci.txt", ci),
                ("requirements.lock", LOCK_HEADER + lock),
            ):
                paths[name] = Path(tmp) / name
                paths[name].write_text(body)
            argv = [
                "check_requirements_sync.py",
                "--requirements", str(paths["requirements.txt"]),
                "--ci-requirements", str(paths["requirements-ci.txt"]),
                "--lock", str(paths["requirements.lock"]),
            ]
            out, err = io.StringIO(), io.StringIO()
            with mock.patch.object(sys, "argv", argv), \
                    contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                code = guard.main()
            return code, out.getvalue() + err.getvalue()

    def test_agreeing_manifests_pass(self):
        code, output = self.run_guard(
            "numpy==2.2.4\npytest>=9.1.1\n",
            "numpy==2.2.4\n",
            lock_line("numpy", "2.2.4") + lock_line("pytest", "9.1.1"),
        )
        self.assertEqual(code, 0, output)

    def test_floor_above_lock_fails(self):
        # The shape of Dependabot #12: the floor moved, the lock did not.
        code, output = self.run_guard(
            "numpy==2.2.4\npytest-asyncio>=1.4.0\n",
            "numpy==2.2.4\n",
            lock_line("numpy", "2.2.4") + lock_line("pytest-asyncio", "1.3.0"),
        )
        self.assertEqual(code, 1)
        self.assertIn("pytest-asyncio: requirements.txt wants >=1.4.0", output)

    def test_release_package_missing_from_lock_fails(self):
        code, output = self.run_guard(
            "numpy==2.2.4\n",
            "numpy==2.2.4\nidna==3.10\n",
            lock_line("numpy", "2.2.4"),
        )
        self.assertEqual(code, 1)
        self.assertIn("idna", output)

    @mock.patch.object(guard, "CI_ONLY_ALLOWED", {"sniffio"})
    def test_allowed_release_only_package_passes(self):
        code, output = self.run_guard(
            "numpy==2.2.4\n",
            "numpy==2.2.4\nsniffio==1.3.1\n",
            lock_line("numpy", "2.2.4"),
        )
        self.assertEqual(code, 0, output)

    def test_repository_manifests_pass(self):
        out = io.StringIO()
        with mock.patch.object(sys, "argv", ["check_requirements_sync.py"]), \
                contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            self.assertEqual(guard.main(), 0, out.getvalue())


if __name__ == "__main__":
    unittest.main()
